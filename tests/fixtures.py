# ---------------------------------------------------------------------------
# Kuhn（Freudenthal）6 四面体剖分：同一单位立方体 [0,1]^3，顶点编号同上。
#
# 6 个单元分别是 3! 条单调路径 0 -> e_p -> e_p+e_q -> 6 的凸包，全部共享
# 体对角线 (0, 6) —— 这是网格中唯一不落在立方体表面上的边（内部边），
# 其星形恰为全部 6 个单元，构成单一闭合邻接环：
#
#     T0-T1 共享 (0,2,6)   T1-T2 共享 (0,3,6)   T2-T3 共享 (0,6,7)
#     T3-T4 共享 (0,4,6)   T4-T5 共享 (0,5,6)   T5-T0 共享 (0,1,6)
#
# 手算核验：对 (0,6,u,v) 有 det(6,u,v) = (u x v)·(1,1,1)，六个单元依次为
# (0,0,1)、(0,0,1)、(1,0,0)、(1,0,0)、(0,1,0)、(0,1,0) 与 (1,1,1) 点积，
# 每个 det = +1，即每个单元体积 +1/6，总体积 1；每单元另两个面落在立方体
# 表面上（共 12 个边界面）。
KUHN_TETS = (
    (0, 6, 1, 2),  # 路径 0-1-2-6
    (0, 6, 2, 3),  # 路径 0-3-2-6
    (0, 6, 3, 7),  # 路径 0-3-7-6
    (0, 6, 7, 4),  # 路径 0-4-7-6
    (0, 6, 4, 5),  # 路径 0-4-5-6
    (0, 6, 5, 1),  # 路径 0-1-5-6
)

