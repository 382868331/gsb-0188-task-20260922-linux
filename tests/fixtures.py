def ring_star_vertices_tets(k):
    """构造一条“星为 k 边形环”的内部边（端点 0、1）。

    k 个链环顶点排在垂直于边 (0,1) 的平面上，单元
    ``(0, 1, 2+j, 2+((j+1) mod k))`` 共 k 个；k>=3 时边严格内部、
    链环为单环。分裂后单元数 2k。全部坐标为小整数 / 有理。
    """

    verts = [(0, 0, 0), (0, 0, 1)]
    verts += [(1, j, Fraction(1, 2)) for j in range(k)]
    tets = tuple((0, 1, 2 + j, 2 + ((j + 1) % k)) for j in range(k))
    return verts, tets


